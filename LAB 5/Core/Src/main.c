/* USER CODE BEGIN 4 */
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
  uint32_t captura_actual;
  uint32_t tiempo_actual;

  //Ver que la interrupción sea canal 1 TIM2
  if ((htim->Instance == TIM2) &&
      (htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1))
  {
    captura_actual = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);
    tiempo_actual = HAL_GetTick();

    //Reiniciar si se pierde la señal
    if ((captura_uno != 0U) ||
        ((tiempo_actual - tiempo_UF) > Timeout_ms))
    {
      captura_ant = captura_actual;
      captura_uno = 0U;
      frecuencia_disp = 0U;
    }
    else
    {
      //Calcular el periodo
      periodo = captura_actual - captura_ant;
      captura_ant = captura_actual;

      //Ver que periodo no sea igual a 0
      if (periodo != 0U)
      {
        frecuencia_disp = 1U;
      }
    }

    tiempo_UF = tiempo_actual;
  }
}

static void Frecuencia_UART(void)
{
  uint32_t periodo_local;
  uint32_t tiempo_flanco_local;
  uint8_t frecuencia_valida_local;
  uint64_t frecuencia_centesimas;
  int longitud;

  //Copiar los valores despues de la interrupción
  periodo_local = periodo;
  tiempo_flanco_local = tiempo_UF;
  frecuencia_valida_local = frecuencia_disp;

  //Ver que haya alguna medición reciente
  if ((frecuencia_valida_local != 0U) &&
      (periodo_local != 0U) &&
      ((HAL_GetTick() - tiempo_flanco_local) <= Timeout_ms))
  {
    //Calcular la frecuencia (2 decimales)
    frecuencia_centesimas =
        (((uint64_t)Contador_f * 100ULL) +
         ((uint64_t)periodo_local / 2ULL)) /
        (uint64_t)periodo_local;

    longitud = snprintf(
        mensaje_uart,
        sizeof(mensaje_uart),
        "Frecuencia: %lu.%02lu Hz\r\n",
        (unsigned long)(frecuencia_centesimas / 100ULL),
        (unsigned long)(frecuencia_centesimas % 100ULL));
  }
  else
  {
    longitud = snprintf(
        mensaje_uart,
        sizeof(mensaje_uart),
        "Frecuencia: sin senal\r\n");
  }

  //Ver que el mensaje si funcione
  if (longitud > 0)
  {
    //Limitar longitud del mensaje
    if ((uint32_t)longitud >= sizeof(mensaje_uart))
    {
      longitud = (int)(sizeof(mensaje_uart) - 1U);
    }

    //Mandar mensaje con USART2
    HAL_UART_Transmit(&huart2,
                      (uint8_t *)mensaje_uart,
                      (uint16_t)longitud,
                      100);
  }
}
